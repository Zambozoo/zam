package build

import (
	"bufio"
	"fmt"
	"io"
	"os"
	"strings"
)

// stdNativePrefix is the convention a native name follows when it is the
// standard library's rather than the project's: the runtime's own table
// answers to any name beginning with it, and the generated wrapper skips
// them so no project is asked to ship a C function for a name the stdlib
// already answers to.
const stdNativePrefix = "STD_"

// writeWrapper writes the one generated C file the per-project link needs:
// the bytecode as a static byte array, the project's native table in slot
// order, and a main that hands them to the runtime and returns the status
// the program's OpExit left behind.
func writeWrapper(path string, image []byte, nativeNames []string) error {
	file, err := os.Create(path)
	if err != nil {
		return fmt.Errorf("cannot create wrapper %q: %w", path, err)
	}
	defer file.Close()

	projectNames := projectNativeNames(nativeNames)

	w := bufio.NewWriter(file)
	writePreamble(w)
	writeImageBytes(w, image)
	writeNativeDeclarations(w, projectNames)
	writeNativeTable(w, projectNames)
	writeMain(w)
	if err := w.Flush(); err != nil {
		return err
	}
	return nil
}

func writePreamble(w *bufio.Writer) {
	fmt.Fprint(w,
		`// Generated by the Zamylene build driver. Do not edit.
//
// This file is the whole of what the compiler adds to the runtime for a
// particular program: the bytecode as a byte array baked into the binary,
// the project's native table, and a main that runs the one and binds the
// other. Everything else is the runtime's own.

#include <stdint.h>
#include <stdio.h>

#include "common.h"
#include "zam/native.h"
#include "vm.h"

`)
}

func writeImageBytes(w *bufio.Writer, image []byte) {
	fmt.Fprint(w,
		`// zam_image_bytes is the compiled image, laid out exactly as it was
// written to disk when --emit-image was asked for. The runtime reads it in
// place: no copy is made and no file is opened, so the binary is also the
// image.
static const uint8_t zam_image_bytes[] = {
`)
	const bytesPerLine = 16
	for i, b := range image {
		if i%bytesPerLine == 0 {
			fmt.Fprint(w, "    ")
		}
		fmt.Fprintf(w, "0x%02x,", b)
		if (i+1)%bytesPerLine == 0 {
			fmt.Fprint(w, "\n")
		} else {
			fmt.Fprint(w, " ")
		}
	}
	if len(image)%bytesPerLine != 0 {
		fmt.Fprint(w, "\n")
	}
	fmt.Fprintf(w, "};\nstatic const size_t zam_image_byte_count = %d;\n\n", len(image))
}

func writeNativeDeclarations(w *bufio.Writer, nativeNames []string) {
	if len(nativeNames) == 0 {
		return
	}
	fmt.Fprint(w,
		`// Every native the compiler saw a reference to is declared here, so the
// linker can tell at link time which names the project forgot to define
// rather than at run time when the first call misses.
`)
	for _, name := range nativeNames {
		if !isValidCSymbol(name) {
			// A name the compiler accepted but that is not a C identifier
			// would not compile here either, so the problem is reported now
			// with the name attached rather than as a syntax error in a file
			// the user did not write.
			fmt.Fprintf(w, "#error \"%q is not a valid C identifier for a native\"\n", name)
			continue
		}
		fmt.Fprintf(w, "extern void %s(ZamThread *thread);\n", name)
	}
	fmt.Fprint(w, "\n")
}

func writeNativeTable(w *bufio.Writer, nativeNames []string) {
	fmt.Fprint(w,
		`// zamProjectNativeTable is the per-project half of what zam_natives_resolve
// searches. The runtime looks up by name against both this table and its own
// standard library table, which is what lets a native(FOO) in .zam source
// bind to a C function the project itself ships.
`)
	if len(nativeNames) == 0 {
		// A C array of zero elements is not standard, so a sentinel entry is
		// written out and the count is kept at zero. The runtime walks the
		// table by count and never reaches the sentinel.
		fmt.Fprint(w,
			`const ZamNativeEntry zamProjectNativeTable[] = {{NULL, NULL}};
const uint64_t zamProjectNativeTableCount = 0;

`)
		return
	}

	fmt.Fprint(w, "const ZamNativeEntry zamProjectNativeTable[] = {\n")
	for _, name := range nativeNames {
		if !isValidCSymbol(name) {
			continue
		}
		fmt.Fprintf(w, "    {%q, %s},\n", name, name)
	}
	fmt.Fprint(w, "};\n")
	fmt.Fprintf(w, "const uint64_t zamProjectNativeTableCount = sizeof(ZamProjectNativeTable) / sizeof(ZamProjectNativeTable[0]);\n\n")
}

func writeMain(w *bufio.Writer) {
	// io.WriteString rather than fmt.Fprint, so the %s inside the embedded
	// C code is not read as a stray Go format directive by vet.
	io.WriteString(w,
		`int main(int argc, const char *argv[]) {
    // The VM is initialised from the baked-in byte array rather than from a
    // file on disk, so the binary is self-contained. Everything after is
    // what the standalone runner does: run to completion, read the status
    // the program's OpExit left on the main thread, and tear the VM down.
    //
    // argv[0] is the program binary's own name; argv[1..argc-1] are what the
    // user passed. Only the latter are the program's own arguments and are
    // handed on as (int, str...) to main.
   ZamVM vm;
    zam_vm_init_from_bytes(&vm, zam_image_bytes, zam_image_byte_count);

   ZamResult result = zam_vm_run(&vm, argc - 1, argv + 1);
    uint8_t status = vm.main.exitStatus;
    zam_vm_free(&vm);

    if (result != ZAMRESULT_EXIT)
        zam_die(ZAMEXIT_PANIC, "the program stopped: %s\n",
                zam_result_name(result));
    return status;
}
`)
}

// projectNativeNames is nativeNames with the standard library's own filtered
// out. The runtime's zamNativeTable is searched first and answers for any
// name the stdlib owns, so a project wrapper that redeclared them would
// collide at link time with the stdlib's own C.
func projectNativeNames(nativeNames []string) []string {
	out := make([]string, 0, len(nativeNames))
	for _, name := range nativeNames {
		if strings.HasPrefix(name, stdNativePrefix) {
			continue
		}
		out = append(out, name)
	}
	return out
}

// isValidCSymbol reports whether name is a legal C identifier. The compiler
// accepts any string as a native name, but a C file that defines one that is
// not a C identifier will not compile, so the check happens here with the
// name in hand rather than at cc time against a syntax error.
func isValidCSymbol(name string) bool {
	if name == "" {
		return false
	}
	for i, r := range name {
		isLetter := (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || r == '_'
		isDigit := r >= '0' && r <= '9'
		if i == 0 && !isLetter {
			return false
		}
		if !isLetter && !isDigit {
			return false
		}
	}
	return true
}
